"""Part-type overhang tables and the classification rules over them.

The YTK table is the one implemented kit: Lee, DeLoache, Cervantes & Dueber,
*ACS Synth. Biol.* 2015 (`sb500366v`), Supplementary Figures S6-S18. Every
overhang is the 4-nt **top-strand** overhang generated by BsaI (``GGTCTC(1/5)``),
written 5'->3'.

The eight part positions close into a circle: type 8 ends on ``CCCT``, which is
where type 1 begins. That circle is the whole model. A part is a contiguous arc
of it, named by the positions it spans, and the arc must not cross the 8/1
boundary - which is what tells a real part from the backbone left over when you
cut one out.

Two enzymes, two jobs
---------------------
Which enzyme cuts decides what the plasmid *is*, whatever its file says:

* the **part enzyme** (BsaI here) releases type 1-8 parts and assembles the
  eight of them into one transcription unit;
* the **multigene enzyme** (BsmBI here) makes part entry vectors and joins
  finished cassettes into a multigene construct.

A `Scheme` binds those two enzymes to a table, so a different kit - MoClo with
its own positions, a Loop-style scheme, an enzyme pair chosen to dodge an
internal site - is a new `Scheme`, not a change to the code that uses one.
Everything here takes `scheme` as a keyword argument defaulting to `YTK`.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .enzymes import BBSI, BSAI, BSMBI, NOTI, Enzyme


@dataclass(frozen=True)
class Scheme:
    """An assembly standard: two enzymes and the overhang circle they run on."""

    name: str
    part_enzyme: Enzyme
    """Releases parts and builds one transcription unit from them."""
    multigene_enzyme: Enzyme
    """Builds part entry vectors, and joins cassettes into a multigene plasmid."""
    linearizer: Enzyme
    """Cuts an integration vector open before transformation."""
    boundaries: tuple[str, ...]
    """Overhangs in order around the circle; the first is repeated at the end."""
    atoms: tuple[str, ...]
    """The indivisible arcs between consecutive boundaries."""
    merges: tuple[tuple[str, str, str], ...] = ()
    """Half-positions that collapse to a whole one: (first, second, whole)."""
    alternate_cloning_enzymes: tuple[Enzyme, ...] = ()
    """Other enzymes a destination vector may use to take an insert, so a part
    carrying an internal site for one of them can still be cloned."""
    entry_vector_overhangs: tuple[str, str] = ()
    """The multigene enzyme's overhangs on the part entry vector."""
    descriptions: dict[str, str] = field(default_factory=dict)
    colors: dict[str, str] = field(default_factory=dict)
    badges: dict[str, tuple[str, str]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if len(self.boundaries) != len(self.atoms) + 1:
            raise ValueError("a scheme needs one more boundary than it has atoms")
        if self.boundaries[0] != self.boundaries[-1]:
            raise ValueError("the boundary list must close the circle")

    @property
    def reserved_overhangs(self) -> frozenset[str]:
        """Overhangs an internally chosen junction must avoid, and not 3-of-4 match."""
        return frozenset(self.entry_vector_overhangs)

    @property
    def overhang_length(self) -> int:
        return self.part_enzyme.overhang_length


