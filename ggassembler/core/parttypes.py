def get_scheme(name: str) -> Scheme:
    try:
        return SCHEMES[name.lower()]
    except KeyError:
        raise ValueError(f"unknown scheme: {name}") from None


@dataclass(frozen=True)
class SpanCall:
    """The arc of the circle that an overhang pair delimits."""

    name: str
    """Canonical part name, e.g. ``3a``, ``234``, ``1234567``."""
    atoms: tuple[str, ...]
    five_prime: str
    three_prime: str
    legal: bool
    """False when the arc crosses the 8/1 boundary - i.e. it is a backbone."""
    reversed_sites: bool = False
    scheme: str = YTK.name

    @property
    def display_name(self) -> str:
        return f"{self.name}r" if self.reversed_sites else self.name

    @property
    def description(self) -> str:
        table = get_scheme(self.scheme).descriptions
        return table.get(self.display_name, table.get(self.name, "composite part"))

    @property
    def is_full_circle(self) -> bool:
        return len(self.atoms) == len(get_scheme(self.scheme).atoms)


def collapse(atoms: tuple[str, ...] | list[str], scheme: Scheme = YTK) -> str:
    """Name an atom run, merging half-positions back into whole ones."""
    parts: list[str] = []
    atoms = list(atoms)
    i = 0
    while i < len(atoms):
        merged = None
        if i + 1 < len(atoms):
            for first, second, whole in scheme.merges:
                if atoms[i] == first and atoms[i + 1] == second:
                    merged = whole
                    break
        if merged:
            parts.append(merged)
            i += 2
        else:
            parts.append(atoms[i])
            i += 1
    return "".join(parts)


def span(
    five_prime: str,
    three_prime: str,
    reversed_sites: bool = False,
    scheme: Scheme = YTK,
) -> SpanCall | None:
    """Resolve an overhang pair to an arc of the circle.

    Returns None when either overhang is not a boundary of this scheme at all,
    and a `SpanCall` with ``legal=False`` when the pair is a real arc but
    crosses the 8/1 boundary - which is what a cut-out backbone looks like.
    """
    five, three = five_prime.upper(), three_prime.upper()
    boundaries = scheme.boundaries
    if five not in boundaries or three not in boundaries:
        return None

    start = boundaries.index(five)
    end = len(boundaries) - 1 - tuple(reversed(boundaries)).index(three)
    if start >= end:
        return SpanCall("", (), five, three, legal=False,
                        reversed_sites=reversed_sites, scheme=scheme.name)

    atoms = scheme.atoms[start:end]
    return SpanCall(
        name=collapse(atoms, scheme),
        atoms=tuple(atoms),
        five_prime=five,
        three_prime=three,
        legal=True,
        reversed_sites=reversed_sites,
        scheme=scheme.name,
    )


def type_overhangs(name: str, scheme: Scheme = YTK) -> tuple[str, str] | None:
    """The (5', 3') overhang pair for a part-type name, e.g. ``234`` or ``3a``."""
    atoms = expand(name, scheme)
    if not atoms:
        return None
    start = scheme.atoms.index(atoms[0])
    end = scheme.atoms.index(atoms[-1]) + 1
    return scheme.boundaries[start], scheme.boundaries[end]


def expand(name: str, scheme: Scheme = YTK) -> tuple[str, ...]:
    """The atoms a part-type name covers. ``3`` -> ``(3a, 3b)``; ``()`` if bad."""
    name = name.strip().rstrip("r")
    wholes = {whole for _, _, whole in scheme.merges}
    atoms: list[str] = []
    i = 0
    while i < len(name):
        token = name[i]
        if i + 1 < len(name) and name[i + 1] in "ab":
            token += name[i + 1]
            i += 2
        else:
            i += 1
        if token in scheme.atoms:
            atoms.append(token)
        elif token in wholes:
            first, second = next((f, s) for f, s, w in scheme.merges if w == token)
            atoms.extend([first, second])
        else:
            return ()
    if not atoms:
        return ()
    indices = [scheme.atoms.index(a) for a in atoms]
    if indices != list(range(indices[0], indices[0] + len(indices))):
        return ()
    return tuple(atoms)


def positions(name: str, scheme: Scheme = YTK) -> list[str]:
    """The whole positions a part-type name covers: ``234`` -> [2, 3, 4]."""
    atoms = expand(name, scheme)
    out: list[str] = []
    for atom in atoms:
        position = atom[0]
        if position not in out:
            out.append(position)
    return out


def is_composite(name: str | None, scheme: Scheme = YTK) -> bool:
    """True for a part spanning more than one position, e.g. ``234`` or ``678``.

    A whole type 3 is not composite: it spans one position, in two halves.
    """
    return bool(name) and len(positions(name, scheme)) > 1


def is_known_type(name: str, scheme: Scheme = YTK) -> bool:
    return bool(expand(name, scheme))


def color_for(part_type: str | None, scheme: Scheme = YTK) -> str:
    """A map colour for a part type, falling back to the first position it spans."""
    if not part_type:
        return "#B0B0B0"
    base = part_type.rstrip("r")
    if base in scheme.colors:
        return scheme.colors[base]
    atoms = expand(base, scheme)
    return scheme.colors.get(atoms[0], "#B0B0B0") if atoms else "#B0B0B0"


def badge_for(part_type: str | None, scheme: Scheme = YTK) -> tuple[str, str]:
    """The (background, foreground) pair a panel badge uses for a part type."""
    if not part_type:
        return ("#E6E4E1", "#3A3A38")
    base = part_type.rstrip("r")
    badges = YTK_BADGES if scheme is YTK else {}
    if base in badges:
        return badges[base]
    atoms = expand(base, scheme)
    position = atoms[0][0] if atoms else ""
    return badges.get(position, ("#E6E4E1", "#3A3A38"))


def near_match(a: str, b: str) -> bool:
    """True when two overhangs are equal or differ at a single position."""
    a, b = a.upper(), b.upper()
    if a == b:
        return True
    if len(a) != len(b):
        return False
    return sum(1 for x, y in zip(a, b, strict=True) if x != y) == 1


def conflicts_with_reserved(overhang: str, scheme: Scheme = YTK) -> str | None:
    """The reserved overhang a chosen junction collides with, if any.

    A junction the app picks itself must avoid the entry vector's overhangs and
    must not 3-of-4 match them.
    """
    for reserved in sorted(scheme.reserved_overhangs):
        if near_match(overhang, reserved):
            return reserved
    return None
